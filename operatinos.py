n = int(input('Введите число: ')) #Ввод числа
n1 = n #Сохраним первоначальное значение n, чтобы после конца цикла вывести его в ответе
i = 0 #Счётчик операций
if 1<=n<=100000:
    while n !=0:
        if n % 3 ==0:
            n -=3
        elif n % 3 ==1:
            n -=1
        else:
            n -=2
        i +=1
    print(f'Требуемое количество операций, для того, чтобы достичь 0 начиная с {n1}: {i}')
else:
    print('Число не входит в диапазон') #Если число не входит в диапазон